create extension if not exists pgcrypto;

create table if not exists public.epro_subject_state (
  subject_id text primary key,
  firebase_uid text,
  patient_name text,
  current_day integer not null default 1 check (current_day >= 1),
  assigned_at timestamptz,
  due_at timestamptz,
  current_questions jsonb not null default '[]'::jsonb,
  trial_complete boolean not null default false,
  updated_at timestamptz not null default timezone('utc', now())
);

comment on table public.epro_subject_state is
  'Current ePRO runtime state keyed by canonical subject_id.';

comment on column public.epro_subject_state.current_questions is
  'The current day questionnaire payload returned to the patient app.';

create index if not exists idx_epro_subject_state_firebase_uid
  on public.epro_subject_state (firebase_uid);

create table if not exists public.mock_patient_profiles (
  patient_id text primary key,
  name text,
  medical_history jsonb not null default '[]'::jsonb,
  vitals_logged jsonb not null default '{"blood_pressure":"Unknown","heart_rate":"Unknown","temperature_celsius":"Unknown"}'::jsonb,
  chat_history jsonb not null default '[]'::jsonb,
  dropout_risk jsonb not null default '{"level":"unknown"}'::jsonb,
  updated_at timestamptz not null default timezone('utc', now())
);

comment on table public.mock_patient_profiles is
  'Testing-phase patient profile context used by the Supabase ePRO edge functions.';

create table if not exists public.patient_daily_logs (
  id uuid primary key default gen_random_uuid(),
  patient_id text not null,
  day_number integer not null check (day_number >= 1),
  answers jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now())
);

comment on table public.patient_daily_logs is
  'Submitted ePRO answers keyed by patient_id and trial day.';

create index if not exists idx_patient_daily_logs_patient_day
  on public.patient_daily_logs (patient_id, day_number desc);

create table if not exists public.dropout_predictions (
  id uuid primary key default gen_random_uuid(),
  firebase_uid text not null,
  subject_id text,
  dropout_subject_id text not null,
  trial_id text,
  scored_at timestamptz not null,
  as_of_day_index integer,
  dropout_probability double precision not null,
  risk_bucket text not null,
  recommended_action text,
  action_priority_score double precision,
  model_version text,
  source_system text not null default 'triallight-dropout-precompute',
  published_at timestamptz not null default timezone('utc', now())
);

comment on table public.dropout_predictions is
  'Historical dropout prediction snapshots generated by scheduled offline scoring.';

create index if not exists idx_dropout_predictions_firebase_uid_published_at
  on public.dropout_predictions (firebase_uid, published_at desc);

create index if not exists idx_dropout_predictions_dropout_subject_id
  on public.dropout_predictions (dropout_subject_id);

create index if not exists idx_dropout_predictions_trial_id
  on public.dropout_predictions (trial_id);

create table if not exists public.dropout_testing_subjects (
  subject_id text primary key,
  trial_id text,
  max_day_index integer not null default 0,
  published_at timestamptz not null default timezone('utc', now())
);

comment on table public.dropout_testing_subjects is
  'Testing-only subject mapping options exposed to CRC patient configuration.';

create index if not exists idx_dropout_testing_subjects_trial_id
  on public.dropout_testing_subjects (trial_id);

